using System;
using System.Collections.Generic;
using Teleop.RobotArm.Kinematics;
using Teleop.RobotArm.Types;

namespace Teleop.RobotArm.Collision
{
    /// <summary>
    /// One capsule of a serial-chain robot's collision model (docs/adr/0026 amendment): a segment from A to B and a radius,
    /// in the frame of what moves it. <see cref="Arm"/> is the arm's index, or -1 for the robot's fixed body. For an arm,
    /// <see cref="Frame"/> -1 is the arm's base (its link 0), and k is joint k's moving frame (link k + 1), as
    /// <see cref="SerialChainKinematics.ComputeFrames"/> numbers them. For the fixed body it is the robot's root.
    /// </summary>
    public readonly struct ChainCapsule
    {
        public readonly string Name;
        public readonly int Arm;
        public readonly int Frame;
        public readonly double Ax, Ay, Az, Bx, By, Bz;
        public readonly double Radius;

        public ChainCapsule(string name, int arm, int frame, double ax, double ay, double az, double bx, double by, double bz, double radius)
        {
            Name = name;
            Arm = arm;
            Frame = frame;
            Ax = ax;
            Ay = ay;
            Az = az;
            Bx = bx;
            By = by;
            Bz = bz;
            Radius = radius;
        }
    }

    /// <summary>What blocked a pose: a joint outside its soft range, or two capsules within the margin.</summary>
    public readonly struct ChainCollisionHit
    {
        public readonly bool IsHit;

        /// <summary>A joint out of range: its arm and index; -1 otherwise.</summary>
        public readonly int Arm, Joint;

        /// <summary>Two capsules too close: their indices in the model; -1 otherwise.</summary>
        public readonly int CapsuleA, CapsuleB;

        /// <summary>The capsules' surface-to-surface distance (negative when they overlap), metres; NaN for a joint hit.</summary>
        public readonly double Distance;

        public ChainCollisionHit(bool isHit, int arm, int joint, int capsuleA, int capsuleB, double distance)
        {
            IsHit = isHit;
            Arm = arm;
            Joint = joint;
            CapsuleA = capsuleA;
            CapsuleB = capsuleB;
            Distance = distance;
        }

        public static readonly ChainCollisionHit None = new ChainCollisionHit(false, -1, -1, -1, -1, double.NaN);
    }

    /// <summary>
    /// A serial-chain robot's collision model (docs/adr/0026 amendment), generated by <c>Teleop.Eval fit-capsules</c> from the
    /// URDF's collision meshes: the capsules, the pairs never checked, and the margin every checked pair must keep.
    /// </summary>
    public sealed class SerialChainCollisionModel
    {
        public string Profile { get; }
        public ChainCapsule[] Capsules { get; }
        public double Margin { get; }

        private readonly bool[] _disabled;

        public SerialChainCollisionModel(string profile, ChainCapsule[] capsules, (int A, int B)[] disabled, double margin)
        {
            Profile = profile;
            Capsules = capsules ?? throw new ArgumentNullException(nameof(capsules));
            if (!(margin >= 0)) throw new ArgumentOutOfRangeException(nameof(margin));
            Margin = margin;
            int n = capsules.Length;
            _disabled = new bool[n * n];
            foreach ((int a, int b) in disabled)
            {
                if (a < 0 || b < 0 || a >= n || b >= n) throw new ArgumentException($"disabled pair ({a}, {b}) is not two capsules of {n}");
                _disabled[a * n + b] = _disabled[b * n + a] = true;
            }

            for (int i = 0; i < n; i++)
            {
                if (!(capsules[i].Radius >= 0)) throw new ArgumentException($"capsule {capsules[i].Name}: negative radius");
            }
        }

        /// <summary>Whether a pair is checked: two different rigid bodies, and not listed as disabled.</summary>
        public bool IsChecked(int a, int b)
        {
            if (a == b) return false;
            ChainCapsule ca = Capsules[a], cb = Capsules[b];
            if (ca.Arm == cb.Arm && ca.Frame == cb.Frame) return false; // one rigid body
            return !_disabled[a * Capsules.Length + b];
        }

        /// <summary>The disabled pairs, each once (a below b).</summary>
        public IEnumerable<(int A, int B)> DisabledPairs()
        {
            int n = Capsules.Length;
            for (int a = 0; a < n; a++)
                for (int b = a + 1; b < n; b++)
                    if (_disabled[a * n + b]) yield return (a, b);
        }
    }

    /// <summary>
    /// Self-collision, arm-to-arm and arm-to-body checks for one robot pose against a <see cref="SerialChainCollisionModel"/>
    /// (docs/adr/0026 amendment). The pose is every arm's joint values, arm after arm in profile order. Deterministic and
    /// allocation-free: the frames and the capsules' world endpoints live on the stack.
    /// </summary>
    public static class SerialChainCollision
    {
        /// <summary>The most frames one arm has (joints + tool), and capsules a model may have, on the stack.</summary>
        public const int MaxFramesPerArm = 16;
        public const int MaxCapsules = 64;

        /// <summary>Whether the pose is allowed: every joint inside its soft range, and every checked pair at least the margin apart.</summary>
        public static bool IsValid(SerialChainProfile profile, SerialChainCollisionModel model, ReadOnlySpan<double> pose) =>
            !Check(profile, model, pose).IsHit;

        /// <summary>As <see cref="IsValid"/>, and says what blocked the pose (the first hit, in a fixed order).</summary>
        public static ChainCollisionHit Check(SerialChainProfile profile, SerialChainCollisionModel model, ReadOnlySpan<double> pose)
        {
            int offset = 0;
            for (int a = 0; a < profile.Arms.Length; a++)
            {
                ChainJoint[] joints = profile.Arms[a].Joints;
                if (pose.Length < offset + joints.Length) throw new ArgumentException("the pose has fewer values than the profile's arms have joints", nameof(pose));
                for (int j = 0; j < joints.Length; j++)
                {
                    double q = pose[offset + j];
                    if (!(q >= joints[j].Limits.SoftLower && q <= joints[j].Limits.SoftUpper)) return new ChainCollisionHit(true, a, j, -1, -1, double.NaN);
                }

                offset += joints.Length;
            }

            int n = model.Capsules.Length;
            if (n > MaxCapsules) throw new ArgumentException($"at most {MaxCapsules} capsules", nameof(model));
            Span<double> world = stackalloc double[MaxCapsules * 6];
            Span<RigidTransform> frames = stackalloc RigidTransform[MaxFramesPerArm];
            offset = 0;
            for (int a = 0; a < profile.Arms.Length; a++)
            {
                ChainArm arm = profile.Arms[a];
                ReadOnlySpan<double> q = pose.Slice(offset, arm.Joints.Length);
                SerialChainKinematics.ComputeFrames(arm, q, frames);
                for (int i = 0; i < n; i++)
                {
                    ChainCapsule c = model.Capsules[i];
                    if (c.Arm != a) continue;
                    RigidTransform f = c.Frame < 0 ? arm.Mount : frames[c.Frame];
                    ToWorld(f, c, world.Slice(i * 6, 6));
                }

                offset += arm.Joints.Length;
            }

            for (int i = 0; i < n; i++)
            {
                ChainCapsule c = model.Capsules[i];
                if (c.Arm < 0) ToWorld(RigidTransform.Identity, c, world.Slice(i * 6, 6));
            }

            for (int i = 0; i < n; i++)
            {
                for (int k = i + 1; k < n; k++)
                {
                    if (!model.IsChecked(i, k)) continue;
                    double d = Math.Sqrt(SegmentDistanceSquared(world.Slice(i * 6, 6), world.Slice(k * 6, 6)))
                        - model.Capsules[i].Radius - model.Capsules[k].Radius;
                    if (d < model.Margin) return new ChainCollisionHit(true, -1, -1, i, k, d);
                }
            }

            return ChainCollisionHit.None;
        }

        /// <summary>
        /// The smallest surface-to-surface distance (m, negative when overlapping) between checked pairs that involve arm
        /// <paramref name="arm"/>'s capsules (any arm's for -1), joint ranges ignored: how far that arm is from touching
        /// anything the model checks. Infinity when no checked pair involves it. Allocation-free, as <see cref="Check"/>.
        /// </summary>
        public static double Clearance(SerialChainProfile profile, SerialChainCollisionModel model, ReadOnlySpan<double> pose, int arm)
        {
            int n = model.Capsules.Length;
            if (n > MaxCapsules) throw new ArgumentException($"at most {MaxCapsules} capsules", nameof(model));
            Span<double> world = stackalloc double[MaxCapsules * 6];
            Span<RigidTransform> frames = stackalloc RigidTransform[MaxFramesPerArm];
            int offset = 0;
            for (int a = 0; a < profile.Arms.Length; a++)
            {
                ChainArm chain = profile.Arms[a];
                if (pose.Length < offset + chain.Joints.Length) throw new ArgumentException("the pose has fewer values than the profile's arms have joints", nameof(pose));
                SerialChainKinematics.ComputeFrames(chain, pose.Slice(offset, chain.Joints.Length), frames);
                for (int i = 0; i < n; i++)
                {
                    ChainCapsule c = model.Capsules[i];
                    if (c.Arm != a) continue;
                    ToWorld(c.Frame < 0 ? chain.Mount : frames[c.Frame], c, world.Slice(i * 6, 6));
                }

                offset += chain.Joints.Length;
            }

            for (int i = 0; i < n; i++)
            {
                ChainCapsule c = model.Capsules[i];
                if (c.Arm < 0) ToWorld(RigidTransform.Identity, c, world.Slice(i * 6, 6));
            }

            double best = double.PositiveInfinity;
            for (int i = 0; i < n; i++)
            {
                for (int k = i + 1; k < n; k++)
                {
                    if (!model.IsChecked(i, k)) continue;
                    if (arm >= 0 && model.Capsules[i].Arm != arm && model.Capsules[k].Arm != arm) continue;
                    double d = Math.Sqrt(SegmentDistanceSquared(world.Slice(i * 6, 6), world.Slice(k * 6, 6)))
                        - model.Capsules[i].Radius - model.Capsules[k].Radius;
                    if (d < best) best = d;
                }
            }

            return best;
        }

        private static void ToWorld(in RigidTransform f, in ChainCapsule c, Span<double> out6)
        {
            f.TransformPoint(c.Ax, c.Ay, c.Az, out out6[0], out out6[1], out out6[2]);
            f.TransformPoint(c.Bx, c.By, c.Bz, out out6[3], out out6[4], out out6[5]);
        }

        /// <summary>The squared distance between segments [p0, p1] and [q0, q1] (each 6 values: start then end).</summary>
        public static double SegmentDistanceSquared(ReadOnlySpan<double> p, ReadOnlySpan<double> q)
        {
            double d1x = p[3] - p[0], d1y = p[4] - p[1], d1z = p[5] - p[2];
            double d2x = q[3] - q[0], d2y = q[4] - q[1], d2z = q[5] - q[2];
            double rx = p[0] - q[0], ry = p[1] - q[1], rz = p[2] - q[2];
            double a = d1x * d1x + d1y * d1y + d1z * d1z;
            double e = d2x * d2x + d2y * d2y + d2z * d2z;
            double f = d2x * rx + d2y * ry + d2z * rz;
            double s, t;
            const double eps = 1e-18;
            if (a <= eps && e <= eps)
            {
                s = t = 0;
            }
            else if (a <= eps)
            {
                s = 0;
                t = Clamp01(f / e);
            }
            else
            {
                double c = d1x * rx + d1y * ry + d1z * rz;
                if (e <= eps)
                {
                    t = 0;
                    s = Clamp01(-c / a);
                }
                else
                {
                    double b = d1x * d2x + d1y * d2y + d1z * d2z;
                    double denom = a * e - b * b;
                    s = denom > eps ? Clamp01((b * f - c * e) / denom) : 0;
                    t = (b * s + f) / e;
                    if (t < 0)
                    {
                        t = 0;
                        s = Clamp01(-c / a);
                    }
                    else if (t > 1)
                    {
                        t = 1;
                        s = Clamp01((b - c) / a);
                    }
                }
            }

            double dx = rx + d1x * s - d2x * t, dy = ry + d1y * s - d2y * t, dz = rz + d1z * s - d2z * t;
            return dx * dx + dy * dy + dz * dz;
        }

        private static double Clamp01(double x) => x < 0 ? 0 : x > 1 ? 1 : x;
    }
}
